CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento VARCHAR(80) NOT NULL UNIQUE,
    nombre VARCHAR(160) NOT NULL,
    correo_corporativo VARCHAR(200) NOT NULL UNIQUE,
    sede VARCHAR(120) NOT NULL,
    area VARCHAR(120) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    rol VARCHAR(40) NOT NULL,
    password_hash VARCHAR(255) NOT NULL
);

CREATE TABLE tecnicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE CHECK (codigo ~ '^TEC-[0-9]{3}$'),
    documento VARCHAR(80) NOT NULL UNIQUE,
    nombre VARCHAR(160) NOT NULL,
    sede VARCHAR(120) NOT NULL,
    carga_maxima INTEGER NOT NULL CHECK (carga_maxima > 0),
    estado VARCHAR(20) NOT NULL,
    usuario_id BIGINT NULL REFERENCES usuarios(id)
);

CREATE TABLE tecnico_especialidades (
    tecnico_id BIGINT NOT NULL REFERENCES tecnicos(id) ON DELETE CASCADE,
    categoria VARCHAR(30) NOT NULL,
    PRIMARY KEY (tecnico_id, categoria)
);

CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitante_id BIGINT NOT NULL REFERENCES usuarios(id),
    tecnico_id BIGINT NULL REFERENCES tecnicos(id),
    titulo VARCHAR(200) NOT NULL,
    descripcion TEXT NOT NULL,
    categoria VARCHAR(30) NOT NULL,
    prioridad VARCHAR(20) NOT NULL,
    sede VARCHAR(120) NOT NULL,
    activo_afectado VARCHAR(200),
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL,
    fecha_limite_sla TIMESTAMP WITH TIME ZONE NOT NULL,
    estado VARCHAR(30) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE historial_ticket (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
    estado_anterior VARCHAR(30),
    estado_nuevo VARCHAR(30) NOT NULL,
    observacion TEXT NOT NULL,
    autor VARCHAR(160) NOT NULL,
    fecha TIMESTAMP WITH TIME ZONE NOT NULL
);
